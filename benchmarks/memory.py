"""Measure how much memory CHIP needs for a range of bits (b) and collisions (C).

For each configuration, runs unbounded CHIP chains on random inputs and records:

- peak Python memory of `Chip.compute`, measured with `tracemalloc`
- raw digest memory: the bytes needed to store every digest (calculated)
- tradeoff memory: the bytes needed by the low-memory method in
  `time_memory_tradeoff.py` (calculated), which is also run to confirm it produces the
  identical digest and to count its extra hashing

Writes memory.csv, memory.md, and memory.png (memory vs. mean iterations, with OWASP's
Argon2id minimum for reference) to the output directory.

Usage: uv run python benchmarks/memory.py [--runs 100]
"""

import argparse
import csv
import os
import secrets
import statistics
import tracemalloc
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from time_memory_tradeoff import INDEX_BYTES, KEY_BYTES, low_memory_chain

from chip import Chip

BITS = (24, 28, 32, 34)
COLLISIONS = (5, 10, 20, 30)
CHECKPOINT = 1000  # iterations between stored digests in the low-memory method
OWASP_ARGON2ID_MB = 19 * 2**20 / 1e6  # OWASP's minimum Argon2id memory, 19 MiB

FIELDS = [
    "bits",
    "collisions",
    "runs",
    "mean_iterations",
    "peak_python_mb",
    "raw_digests_mb",
    "tradeoff_mb",
    "tradeoff_extra_hashing_pct",
]


def run_once(bits: int, collisions: int) -> tuple[int, int, int, int, int]:
    """Return (iterations, peak Python bytes, raw bytes, tradeoff bytes, extra hashes)."""
    chip = Chip(bits=bits, collisions=collisions)
    data = secrets.token_bytes(16) + b"hunter2"

    tracemalloc.start()
    chain = chip.compute(data, bounded=False)
    peak = tracemalloc.get_traced_memory()[1]
    tracemalloc.stop()

    digest, iterations, extra, checkpoints = low_memory_chain(
        data, bits, collisions, chip.hash_func, CHECKPOINT
    )
    assert digest == chain.digest, "low-memory digest differs from Chip.compute"

    stored = iterations - collisions  # digests kept by Chip.compute
    digest_size = len(digest)
    raw = stored * digest_size
    tradeoff = stored * (KEY_BYTES + INDEX_BYTES) + checkpoints * digest_size
    return iterations, peak, raw, tradeoff, extra


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--runs", type=int, default=100)
    parser.add_argument("--workers", type=int, default=os.cpu_count())
    parser.add_argument("--out", type=Path, default=Path(__file__).parent / "results")
    args = parser.parse_args()

    rows = []
    with ProcessPoolExecutor(args.workers) as pool:
        for bits in BITS:
            for collisions in COLLISIONS:
                results = list(pool.map(run_once, [bits] * args.runs, [collisions] * args.runs))
                iterations, peak, raw, tradeoff, extra = zip(*results, strict=True)
                row = {
                    "bits": bits,
                    "collisions": collisions,
                    "runs": args.runs,
                    "mean_iterations": round(statistics.mean(iterations)),
                    "peak_python_mb": round(statistics.mean(peak) / 1e6, 1),
                    "raw_digests_mb": round(statistics.mean(raw) / 1e6, 1),
                    "tradeoff_mb": round(statistics.mean(tradeoff) / 1e6, 1),
                    "tradeoff_extra_hashing_pct": round(100 * sum(extra) / sum(iterations), 1),
                }
                rows.append(row)
                print(
                    f"b={bits} C={collisions:2d}  iterations {row['mean_iterations']:>9,}  "
                    f"python {row['peak_python_mb']:6.1f} MB  raw {row['raw_digests_mb']:5.1f} MB  "
                    f"tradeoff {row['tradeoff_mb']:4.1f} MB",
                    flush=True,
                )

    args.out.mkdir(parents=True, exist_ok=True)
    with (args.out / "memory.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)
    (args.out / "memory.md").write_text(markdown(rows, args.runs))
    plot(args.out / "memory.png", rows)
    print(f"Wrote memory.csv, memory.md, and memory.png to {args.out}")


def markdown(rows: list[dict[str, int | float]], runs: int) -> str:
    lines = [
        f"Memory per chain, averaged over {runs:,} runs per row. "
        "Generated by `benchmarks/memory.py`.",
        "",
        "- **Peak Python** is measured with `tracemalloc` while `Chip.compute` runs.",
        "- **Raw digests** is calculated: every stored digest at its byte size.",
        "- **Tradeoff** is calculated for the low-memory method in "
        "`time_memory_tradeoff.py` (4-byte keys and indices, plus a digest every "
        f"{CHECKPOINT:,} iterations), which was run and produced identical digests.",
        "",
        "| b | C | Mean iterations | Peak Python | Raw digests | Tradeoff | "
        "Tradeoff extra hashing |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['bits']} | {r['collisions']} | {r['mean_iterations']:,} | "
            f"{r['peak_python_mb']} MB | {r['raw_digests_mb']} MB | {r['tradeoff_mb']} MB | "
            f"{r['tradeoff_extra_hashing_pct']}% |"
        )
    return "\n".join(lines) + "\n"


def plot(path: Path, rows: list[dict[str, int | float]]) -> None:
    # Imported here so worker processes don't pay for loading matplotlib.
    import matplotlib

    matplotlib.use("Agg")  # render to files, no window
    import matplotlib.pyplot as plt

    rows = sorted(rows, key=lambda r: r["mean_iterations"])
    x = [r["mean_iterations"] for r in rows]
    fig, ax = plt.subplots(figsize=(8, 5), dpi=150)
    for key, label in [
        ("peak_python_mb", "Peak Python (measured)"),
        ("raw_digests_mb", "Raw digests (calculated)"),
        ("tradeoff_mb", "With time-memory tradeoff (calculated)"),
    ]:
        ax.plot(x, [r[key] for r in rows], marker="o", markersize=3, label=label)
    ax.axhline(OWASP_ARGON2ID_MB, color="gray", linestyle="--", linewidth=1)
    ax.annotate(
        "OWASP minimum for Argon2id (19 MiB)",
        (x[0], OWASP_ARGON2ID_MB),
        xytext=(0, 4),
        textcoords="offset points",
        color="gray",
        fontsize=9,
    )
    ax.xaxis.set_major_formatter(lambda value, _: f"{value:,.0f}")
    ax.set_title("CHIP memory by chain length")
    ax.set_xlabel("Mean iterations per chain")
    ax.set_ylabel("Memory (MB)")
    ax.grid(True, alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


if __name__ == "__main__":
    main()
