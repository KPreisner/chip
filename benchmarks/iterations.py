"""Measure how many iterations CHIP takes for each combination of bits (b) and collisions (C).

For each `bits` value, runs unbounded CHIP chains with random inputs and records the
iteration count at each collision, so one run with C = 8 fills all eight columns.
Writes to the output directory:

- iterations.csv  mean and standard deviation for every (bits, collisions) pair
- iterations.md   Markdown tables of the means and standard deviations
- iterations.png  mean iterations vs. bits, one line per collision count

Usage: uv run python benchmarks/iterations.py [--min-bits 10] [--max-bits 32] [--runs 1000]
"""

import argparse
import csv
import os
import secrets
import statistics
from concurrent.futures import Executor, ProcessPoolExecutor
from pathlib import Path

from chip import Chip


def run_once(bits: int, collisions: int) -> tuple[int, ...]:
    """Iteration count at each collision for one random input."""
    chip = Chip(bits=bits, collisions=collisions)
    return chip.compute(secrets.token_bytes(16), bounded=False).collision_iterations


def measure(pool: Executor, bits: int, collisions: int, runs: int) -> list[tuple[int, ...]]:
    # Send runs to workers in batches; one-at-a-time messaging dominates for small b.
    chunksize = max(1, runs // 50)
    return list(pool.map(run_once, [bits] * runs, [collisions] * runs, chunksize=chunksize))


def write_csv(path: Path, means: dict[int, list[float]], stds: dict[int, list[float]]) -> None:
    with path.open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["bits", "collisions", "mean", "std"])
        for bits in means:
            for c, (mean, std) in enumerate(zip(means[bits], stds[bits], strict=True), start=1):
                writer.writerow([bits, c, round(mean), round(std)])


def markdown_table(title: str, rows: dict[int, list[str]], collisions: int) -> str:
    header = "| b \\ C | " + " | ".join(str(c) for c in range(1, collisions + 1)) + " |"
    divider = "|---" * (collisions + 1) + "|"
    lines = [f"### {title}", "", header, divider]
    lines += [f"| {bits} | " + " | ".join(cells) + " |" for bits, cells in rows.items()]
    return "\n".join(lines) + "\n"


def write_markdown(
    path: Path,
    means: dict[int, list[float]],
    stds: dict[int, list[float]],
    collisions: int,
    runs: int,
) -> None:
    mean_cells = {bits: [f"{m:,.0f}" for m in row] for bits, row in means.items()}
    std_cells = {bits: [f"{s:,.0f}" for s in row] for bits, row in stds.items()}
    sections = [
        f"Results from {runs:,} runs per row. Generated by `benchmarks/iterations.py`.\n",
        markdown_table("Mean iterations", mean_cells, collisions),
        markdown_table("Standard deviation", std_cells, collisions),
    ]
    path.write_text("\n".join(sections))


def plot(path: Path, means: dict[int, list[float]], collisions: int) -> None:
    # Imported here so worker processes don't pay for loading matplotlib.
    import matplotlib

    matplotlib.use("Agg")  # render to files, no window
    import matplotlib.pyplot as plt

    bits = list(means)
    fig, ax = plt.subplots(figsize=(8, 5), dpi=150)
    for c in range(collisions):
        ax.plot(bits, [means[b][c] for b in bits], marker="o", markersize=3, label=f"C = {c + 1}")
    ax.set_yscale("log")
    ax.yaxis.set_major_formatter(lambda value, _: f"{value:,.0f}")
    ax.set_xlabel("Bits compared, b")
    ax.set_ylabel("Mean iterations (log scale)")
    ax.set_title("CHIP iterations by bits (b) and collisions (C)")
    ax.grid(True, which="major", alpha=0.3)
    handles, labels = ax.get_legend_handles_labels()
    ax.legend(handles[::-1], labels[::-1], title="Collisions")  # top-to-bottom like the lines
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--min-bits", type=int, default=10)
    parser.add_argument("--max-bits", type=int, default=32)
    parser.add_argument("--collisions", type=int, default=8)
    parser.add_argument("--runs", type=int, default=1000)
    parser.add_argument("--workers", type=int, default=os.cpu_count())
    parser.add_argument("--out", type=Path, default=Path(__file__).parent / "results")
    args = parser.parse_args()

    means: dict[int, list[float]] = {}
    stds: dict[int, list[float]] = {}
    with ProcessPoolExecutor(args.workers) as pool:
        for bits in range(args.min_bits, args.max_bits + 1):
            results = measure(pool, bits, args.collisions, args.runs)
            columns = list(zip(*results, strict=True))  # one column per collision count
            means[bits] = [statistics.mean(col) for col in columns]
            stds[bits] = [statistics.pstdev(col) for col in columns]
            print(f"b={bits:2d}  C={args.collisions} mean {means[bits][-1]:>10,.0f}", flush=True)

    args.out.mkdir(parents=True, exist_ok=True)
    write_csv(args.out / "iterations.csv", means, stds)
    write_markdown(args.out / "iterations.md", means, stds, args.collisions, args.runs)
    plot(args.out / "iterations.png", means, args.collisions)
    print(f"Wrote iterations.csv, iterations.md, iterations.png to {args.out}")


if __name__ == "__main__":
    main()
